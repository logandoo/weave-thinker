            "核心判断标准：这句话是不是用户**直接对助手说的、需要助手停下回应的**插话。"
            "回答一个词：\n"
            "- interrupt：用户在直接对助手提出新问题、新请求、否定、纠正、要求停止/暂停当前播报、"
