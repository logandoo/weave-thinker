            "绝不能因为话题无关就把用户对助手说的新话题误判成背景噪音。**"
            "即使只有一个词，只要携带明确语义或在上下文中是有意义的回应就回应。\n"
            "判断原则（ASR 不可靠，请结合上下文）：\n"
            "1) 先看上下文。如果这句话能自然接续最近一轮对话（如用户在追问、补充、确认、"
            "表达对刚才回答的看法），应判 true。\n"
            "2) 如果这句话与对话主题完全脱节，判 false 的唯一依据是**它不是在对助手说话**"
