    def _get_next_pending_step(self) -> Optional[Dict[str, Any]]:
        """Return the first step that is pending or in_progress, respecting
        dependencies. Returns None if all steps are done.

        R2（诊断机制 A）：stuck 步骤不得垄断步骤机——存在其他可行动候选时
        跳过 stuck 候选，仅在无其他候选时兜底重拾（无空转）。"""
        _sync_deathmatchworkspace_globals()
        plan = self._conv.deathmatch_plan
        if not plan or not isinstance(plan, dict):
            return None
        steps = plan.get("steps") or []
        done_ids = {s.get("id") for s in steps if s.get("status") == "done"}
        # First, check if any step is already in_progress — resume it.
        for s in steps:
            if s.get("status") == "in_progress":
                return s
        # Find the first non-stuck pending step whose dependencies are all done.
        for s in steps:
            if s.get("status") != "pending" or s.get("stuck"):
                continue
            deps = s.get("dependencies") or []
            if all(d in done_ids for d in deps):
                return s
        # R2/I2（评审）：stuck 且依赖满足 = 当前唯一可行动工作——重拾它，
        # 不得跳到依赖未满足的后续步（依赖序是正确性，不是建议）。
        for s in steps:
            if s.get("status") != "pending" or not s.get("stuck"):
                continue
            deps = s.get("dependencies") or []
            if all(d in done_ids for d in deps):
                return s
        # Legacy fallback: no dep-satisfied candidate (broken/unknown deps) —
        # first non-stuck pending, then a stuck one.
        for s in steps:
            if s.get("status") == "pending" and not s.get("stuck"):
                return s
        for s in steps:
            if s.get("status") == "pending":
                return s
        return None
