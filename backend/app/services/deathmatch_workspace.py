def _goal_contract_sections(goal: str) -> tuple[str, str]:
    """Return (correction, original baseline) without duplication."""
    text = str(goal or "")
    correction = ""
    correction_marker = "【最新恢复纠正"
    if correction_marker in text:
        correction = text[text.index(correction_marker):]
        for next_heading in ("【原始用户要求", "【实际盘问决策", "【已采用的默认假设", "【此前对话上下文"):
            if next_heading in correction:
                correction = correction.split(next_heading, 1)[0]
                break
        correction = correction.strip()
    marker = "【原始用户要求"
    if marker in text:
        section = text[text.index(marker):]
        for next_heading in (
            "【最新恢复纠正", "【实际盘问决策", "【已采用的默认假设", "【此前对话上下文",
        ):
            if next_heading in section:
                section = section.split(next_heading, 1)[0]
                break
        baseline = section.strip()
    else:
        baseline = text.split(correction_marker, 1)[0].strip() if correction else text.strip()
    return correction, baseline


def _goal_baseline_for_contract(goal: str) -> str:
    """Use original requirements plus all authoritative resume corrections."""
    correction, baseline = _goal_contract_sections(goal)
    # The newest correction comes first so every head-bounded downstream
    # planner/auditor/classifier sees it before older requirements.
    return "\n\n".join(part for part in (correction, baseline) if part)


def _workspace_realpath(path: Any, workspace_path: str) -> str:
    """Resolved in-workspace file path, or '' on escape/invalid input."""
    if not workspace_path:
        return ""
    raw = str(path or "").strip()
    if not raw:
        return ""
    workspace_real = _os.path.realpath(workspace_path)
    candidate = raw if _os.path.isabs(raw) else _os.path.join(workspace_real, raw)
    resolved = _os.path.realpath(candidate)
    try:
        if _os.path.commonpath([workspace_real, resolved]) != workspace_real:
            return ""
    except ValueError:
        return ""
    return resolved


def _normalize_exact_file_criteria(
    criteria: List[Dict[str, Any]],
) -> tuple[Optional[List[Dict[str, Any]]], List[Dict[str, Any]], Optional[Dict[str, str]]]:
    """Validate structured exact content and repair only provable minima.

    Legacy shell cmp candidates are rejected as a whole and regenerated by the
    caller. No shell parsing, expansion, command-position or path guessing is
    involved, and a rejected candidate can never persist a weakened remainder.
    """
    has_gate = any(
        isinstance(c, dict) and (c.get("check") or {}).get("kind") == "gate"
        for c in criteria or []
    )
    if has_gate:
        return None, [], {"reason": "legacy_gate_requires_structured_check"}

    exact: Dict[str, bytes] = {}
    for criterion in criteria or []:
        check = criterion.get("check") if isinstance(criterion, dict) else None
        if not isinstance(check, dict) or check.get("kind") != "exact_file":
            continue
        path = _normalize_rel_path(_safe_exact_file_path(_normalize_rel_path(check.get("path"))))
        content = check.get("content")
        if not path or not isinstance(content, str) or len(content) > 200000:
            return None, [], {"reason": "invalid_exact_file_shape"}
        try:
            path.encode("utf-8")
            expected = content.encode("utf-8")
        except UnicodeEncodeError:
            return None, [], {"reason": "invalid_exact_file_unicode"}
        previous = exact.get(path)
        if previous is not None and previous != expected:
            return None, [], {"reason": "conflicting_exact_file_payloads", "path": path}
        exact[path] = expected

    kept: List[Dict[str, Any]] = []
    normalized: List[Dict[str, Any]] = []
    for criterion in criteria or []:
        check = criterion.get("check") if isinstance(criterion, dict) else None
        if not isinstance(check, dict) or check.get("kind") != "file":
            kept.append(criterion)
            continue
        path = _normalize_rel_path(check.get("path"))
        expected = exact.get(path)
        try:
            minimum = max(0, int(check.get("min_bytes") or 0))
        except (TypeError, ValueError):
            minimum = 0
        if expected is not None and minimum > len(expected):
            updated = dict(criterion)
            updated_check = dict(check)
            updated_check["min_bytes"] = len(expected)
            updated["check"] = updated_check
            updated["text"] = (
                f"文件 {check.get('path')} 存在且不少于 {len(expected)} 字节"
                "（由结构化精确内容计算）"
            )
            kept.append(updated)
            normalized.append({
                "criterion": str(criterion.get("id") or ""),
                "min_bytes": minimum, "new_min_bytes": len(expected),
                "exact_bytes": len(expected),
            })
            continue
        kept.append(criterion)
    return kept, normalized, None


class DeathmatchWorkspaceMixin:
    async def _synthesize_acceptance_criteria(self) -> List[Dict[str, Any]]:
        """W1a: draft the acceptance criteria right after goal synthesis.
        Fail-open: LLM failure leaves the legacy prose-goal behavior intact
        (and empties the stored criteria so no stale contract survives)."""
        _sync_deathmatchworkspace_globals()
        if not config.deathmatch_criteria_enabled:
            return []
        correction, baseline = _goal_contract_sections(self._conv.deathmatch_goal or "")
        # Independent windows prevent a long correction from starving the
        # original hard requirements. _truncate discloses every clipped section.
        goal = "\n\n".join(
            part for part in (
                _truncate(correction, 1800) if correction else "",
                _truncate(baseline, 1800),
            ) if part
        )
        if not goal.strip():
            return []
        try:
            # Latest decisions/defaults must enter the bounded criteria window;
            # the original baseline has its own reserved section above.
            qa = self._format_history_for_prompt(newest_first=True)
            llm = self._make_llm()
            user_prompt = (
                f"用户目标:\n{goal}\n\n"
                f"盘问问答（最新优先）:\n{qa[:2000] if qa else '(无)'}\n\n"
                "请起草验收标准并输出 JSON。"
            )
            raw = await self._llm_generate(
                llm, self.CRITERIA_SYSTEM_PROMPT, user_prompt, temperature=0.2,
            )
            try:
                crit = _parse_criteria_response(raw)
            except CriteriaCandidateRejected as exc:
                if exc.reason not in ("malformed_json", "empty_criteria"):
                    raise
                # A malformed model reply is a recoverable transport/shape
                # failure. Retry the same contract once; semantic invalidity
                # still pauses immediately and never gets an LLM repair pass.
                self._record_event("criteria_retry", reason=exc.reason)
                raw = await self._llm_generate(
                    llm, self.CRITERIA_SYSTEM_PROMPT, user_prompt, temperature=0.2,
                )
                crit = _parse_criteria_response(raw)
            crit, normalized, rejected = _normalize_exact_file_criteria(crit)
            if rejected:
                self._record_event("criteria_rejected", stage="initial", **rejected)
                self._conv.deathmatch_acceptance_criteria = None
                reason = str(rejected.get("reason") or "invalid_exact_file_contract")
                self.pause(f"验收标准生成失败：{reason}；请重试或调整目标")
                self._record_event(
                    "criteria_synthesized", count=0,
                    error=reason,
                )
                return []
            for item in normalized:
                self._record_event(
                    "criteria_normalized",
                    reason="min_bytes_exceeds_exact_file_content",
                    **item,
                )
            self._conv.deathmatch_acceptance_criteria = crit or None
            self._record_event(
                "criteria_synthesized",
                count=len(crit),
                contract_hash=_contract_hash(goal, crit) if crit else "",
            )
            return crit
        except CriteriaCandidateRejected as exc:
            self._record_event("criteria_rejected", stage="initial", reason=exc.reason)
            self._conv.deathmatch_acceptance_criteria = None
            self.pause(f"验收标准生成失败：{exc.reason}；请重试或调整目标")
            self._record_event("criteria_synthesized", count=0, error=exc.reason)
            return []
        except Exception as exc:
            logger.warning("acceptance criteria synthesis failed (fail-open): %s", exc)
            self._conv.deathmatch_acceptance_criteria = None
            self._record_event("criteria_synthesized", count=0, error=str(exc)[:120])
            return []
